#!/bin/bash
# Check status of the remote service

REMOTE_HOST="${REMOTE_HOST:-dell-cloudflare}"
REMOTE_USER="${REMOTE_USER:-$USER}"
SERVICE_NAME="elevator-system"

echo "Checking status on ${REMOTE_HOST}..."
echo ""

ssh "${REMOTE_USER}@${REMOTE_HOST}" bash << REMOTE_SCRIPT
set -e

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Service Status"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
sudo systemctl status ${SERVICE_NAME} --no-pager || true

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Recent Logs (last 20 lines)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
sudo journalctl -u ${SERVICE_NAME} -n 20 --no-pager

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Health Check"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s http://localhost:8000/health | python3 -m json.tool || echo "Health check failed"
REMOTE_SCRIPT
